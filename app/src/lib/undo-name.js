// @ts-check
// The name of an undo step in the diver's language. The core names its steps as Subsurface
// does, in English (« add 2 dives to trip [#3, #4] », core/libopendives/edit.cpp); the
// desktop's « Annuler : {dernière action} » (tasks 2026-11-15-179 and 192) shows this name.

/** Core texts, in the order they are tried, and the i18n key of their name. */
const NAMES = /** @type {[RegExp, string][]} */ ([
  [/^Edit trip /, 'desktop.undo.editTrip'],
  [/^Edit dive site /, 'desktop.undo.editSite'],
  [/^Edit filter preset /, 'desktop.undo.filters'],
  [/^(Create|Delete) filter preset /, 'desktop.undo.filters'],
  [/^Edit /, 'desktop.undo.editDive'],
  [/^add dive site/, 'desktop.undo.addSite'],
  [/^add dive$/, 'desktop.undo.addDive'],
  [/^add \d+ dives? to trip/, 'desktop.undo.addToTrip'],
  [/^remove \d+ dive\(s\) from trip/, 'desktop.undo.removeFromTrip'],
  [/^create trip/, 'desktop.undo.createTrip'],
  [/^merge trips/, 'desktop.undo.mergeTrips'],
  [/^autogroup dives/, 'desktop.undo.autogroup'],
  [/^remove autogenerated trips/, 'desktop.undo.ungroup'],
  [/^merge dive sites/, 'desktop.undo.mergeSites'],
  [/^delete (%n|\d+) dive site/, 'desktop.undo.deleteSites'],
  [/^delete \d+ dive/, 'desktop.undo.deleteDives'],
  [/^import /, 'desktop.undo.import'],
  [/^renumber /, 'desktop.undo.renumber'],
  [/^Rename cylinder type/, 'desktop.undo.cylinderType'],
  [/^(Set nickname of device|merge dive computer|remove dive computer|move dive computer to front)/, 'desktop.undo.computers'],
  [/^replan dive/, 'desktop.undo.replan'],
]);

/**
 * The i18n key naming a core undo step, or '' when it is not known (the menu then says
 * « Annuler la dernière action »).
 * @param {string} text the core's step text (logbook.undoText, logbook.redoText)
 * @returns {string}
 */
export function undoNameKey(text) {
  if (!text) return '';
  return NAMES.find(([pattern]) => pattern.test(text))?.[1] ?? '';
}
