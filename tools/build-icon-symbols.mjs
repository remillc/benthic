// Regenerates the `symbols` table of app/src/components/Icon.svelte from Google's Material Symbols (Rounded, weight 400,
// grade 0, optical size 24, unfilled; viewBox 0 -960 960 960). Tasks 2026-11-23-364 and 365.
//
// Usage: node tools/build-icon-symbols.mjs
// Each glyph is fetched from
//   https://raw.githubusercontent.com/google/material-design-icons/master/symbols/web/<name>/materialsymbolsrounded/<name>_24px.svg
// and its path data is written between the two marker comments of Icon.svelte. The keys of `KEYS` are the keys of Icon.svelte,
// the values the Material Symbols names. A key that is in `symbols` must not be in `paths`: the script stops if it is.
import { readFileSync, writeFileSync } from 'node:fs';

const KEYS = {
  archive: 'archive', arrowBack: 'arrow_back', arrowDown: 'arrow_downward', arrowRight: 'arrow_forward', arrowUp: 'arrow_upward',
  bell: 'notifications', bluetooth: 'bluetooth', bluetoothOff: 'bluetooth_disabled', book: 'book', briefcase: 'work',
  calendar: 'calendar_today', camera: 'photo_camera', check: 'check', checkCircle: 'check_circle', chevron: 'chevron_right',
  clock: 'schedule', close: 'close', cloud: 'cloud', cloudCheck: 'cloud_done', cloudDownload: 'cloud_download',
  cloudUpload: 'cloud_upload', columns: 'view_column', copy: 'content_copy', delete: 'delete', desaturation: 'timer',
  device: 'smartphone', document: 'description', download: 'download', edit: 'edit', error: 'error',
  exitFullscreen: 'fullscreen_exit', expand: 'expand_more', export: 'upload', file: 'draft', filter: 'filter_list',
  folder: 'folder', fullscreen: 'fullscreen', globe: 'language', history: 'history', idCard: 'id_card', image: 'image',
  info: 'info', key: 'key', keyboard: 'keyboard', lightbulb: 'lightbulb', link: 'link', locate: 'my_location', lock: 'lock',
  login: 'login', logout: 'logout', mail: 'mail', map: 'map', menu: 'menu', merge: 'merge', more: 'more_vert',
  moreCircle: 'pending', offline: 'cloud_off', openInNew: 'open_in_new', personAdd: 'person_add', phone: 'smartphone',
  pinOff: 'location_off', place: 'location_on', plane: 'flight', plus: 'add', profile: 'person', qr: 'qr_code_2',
  redo: 'redo', refresh: 'refresh', remove: 'do_not_disturb_on', renumber: 'tag', seal: 'verified', search: 'search',
  server: 'dns', settings: 'settings', share: 'share', sites: 'location_on', split: 'call_split', statistics: 'bar_chart',
  sync: 'sync', tablet: 'tablet_android', tools: 'tune', trash: 'delete', tune: 'tune', undo: 'undo', upload: 'upload',
  visibility: 'visibility', visibilityOff: 'visibility_off', warning: 'warning', wrench: 'build',
  // Desktop dive detail, Informations tab (task 2026-11-23-376).
  people: 'group', star: 'star', tag: 'sell', waves: 'waves',
};

const file = new URL('../app/src/components/Icon.svelte', import.meta.url);
let source = readFileSync(file, 'utf8');
const begin = '  // <symbols generated by tools/build-icon-symbols.mjs>\n';
const end = '  // </symbols>\n';

const names = [...new Set(Object.values(KEYS))];
const glyphs = {};
for (const name of names) {
  const url = `https://raw.githubusercontent.com/google/material-design-icons/master/symbols/web/${name}/materialsymbolsrounded/${name}_24px.svg`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${name}: HTTP ${res.status}`);
  const svg = await res.text();
  if (!svg.includes('viewBox="0 -960 960 960"')) throw new Error(`${name}: unexpected viewBox`);
  const d = [...svg.matchAll(/<path[^>]* d="([^"]+)"/g)].map((m) => m[1]).join('');
  if (!d) throw new Error(`${name}: no path`);
  glyphs[name] = d;
}

const body = Object.entries(KEYS)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([key, name]) => `    ${key}: '${glyphs[name]}', // ${name}`)
  .join('\n');
const from = source.indexOf(begin);
const to = source.indexOf(end);
if (from < 0 || to < 0) throw new Error('markers not found in Icon.svelte');
source = source.slice(0, from + begin.length) + `  /** @type {Record<string, string>} */\n  const symbols = {\n${body}\n  };\n` + source.slice(to);

// A key may not be in both tables.
const pathsBlock = source.slice(source.indexOf('const paths = {'), source.indexOf('};', source.indexOf('const paths = {')));
for (const key of Object.keys(KEYS)) if (new RegExp(`^\s*${key}: '`, 'm').test(pathsBlock)) throw new Error(`${key} is still in paths`);

writeFileSync(file, source);
console.log(`${Object.keys(KEYS).length} keys, ${names.length} glyphs written`);
